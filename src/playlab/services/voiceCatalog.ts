/**
 * Pure helpers for choosing a browser (Web Speech API) voice. No browser APIs are touched here,
 * so everything is easy to unit test. Nothing in this file calls a network service.
 */

/** The parts of a SpeechSynthesisVoice we rely on (kept minimal so tests can pass plain objects). */
export interface VoiceLike {
  name: string;
  lang: string;
  voiceURI?: string;
  localService?: boolean;
}

/** One selectable English voice. */
export interface VoiceOption {
  /** Stable id used for saving: the voiceURI, or "name|lang" when a browser provides none. */
  id: string;
  name: string;
  /** normalised BCP-47, e.g. "en-US" */
  lang: string;
  /** e.g. "Samantha (American English)" or "Google UK English Female (British English, online)" */
  label: string;
  american: boolean;
  /** true when the voice is generated by an online service (SpeechSynthesisVoice.localService === false) */
  online: boolean;
}

/** "en_US", "EN-us", "en" -> "en-US" / "en". */
export function normalizeLang(lang: string | undefined): string {
  const [language = '', region] = String(lang ?? '').replace(/_/g, '-').split('-');
  return region ? `${language.toLowerCase()}-${region.toUpperCase()}` : language.toLowerCase();
}

export const isEnglish = (lang: string | undefined): boolean => normalizeLang(lang).split('-')[0] === 'en';

const ACCENTS: Record<string, string> = {
  'en-US': 'American English',
  'en-GB': 'British English',
  'en-AU': 'Australian English',
  'en-CA': 'Canadian English',
  'en-IN': 'Indian English',
  'en-IE': 'Irish English',
  'en-NZ': 'New Zealand English',
  'en-ZA': 'South African English',
};

/** Accent name when we recognise the region, otherwise just "English". */
export const accentName = (lang: string): string => ACCENTS[normalizeLang(lang)] ?? 'English';

export const voiceId = (v: VoiceLike): string => v.voiceURI || `${v.name}|${v.lang}`;

const toOption = (v: VoiceLike): VoiceOption => {
  const lang = normalizeLang(v.lang);
  const online = v.localService === false;
  return {
    id: voiceId(v),
    name: v.name,
    lang,
    american: lang === 'en-US',
    online,
    label: `${v.name} (${accentName(lang)}${online ? ', online' : ''})`,
  };
};

const rank = (o: VoiceOption): number => (o.american ? 0 : 2) + (o.online ? 1 : 0);

/**
 * Every English voice the device offers, de-duplicated and ordered:
 * American on-device, American online, other English on-device, other English online (then by name).
 * Nothing is excluded other than non-English voices.
 */
export function listEnglishVoices(raw: readonly VoiceLike[]): VoiceOption[] {
  const seen = new Set<string>();
  const out: VoiceOption[] = [];
  for (const v of raw) {
    if (!isEnglish(v.lang)) continue;
    const o = toOption(v);
    if (seen.has(o.id)) continue;
    seen.add(o.id);
    out.push(o);
  }
  return out.sort((a, b) => rank(a) - rank(b) || a.name.localeCompare(b.name));
}

/**
 * Automatic choice for `lang`: an exact language match first, otherwise any voice of the same language;
 * on-device voices are preferred (they work offline and send nothing to a vendor service).
 */
export function pickAutoVoice<T extends VoiceLike>(raw: readonly T[], lang: string): T | null {
  const want = normalizeLang(lang);
  const base = want.split('-')[0];
  const exact = raw.filter((v) => normalizeLang(v.lang) === want);
  const loose = raw.filter((v) => normalizeLang(v.lang).split('-')[0] === base);
  const pool = exact.length ? exact : loose;
  return pool.find((v) => v.localService !== false) ?? pool[0] ?? null;
}

/**
 * The voice to use for a request: the saved/selected English voice if it exists on this device,
 * otherwise the automatic choice. A stale or unknown id silently falls back to automatic.
 * The saved voice only applies to English requests.
 */
export function resolveVoice<T extends VoiceLike>(raw: readonly T[], lang: string, preferredId: string | null | undefined): T | null {
  if (preferredId && isEnglish(lang)) {
    const chosen = raw.find((v) => isEnglish(v.lang) && voiceId(v) === preferredId);
    if (chosen) return chosen;
  }
  return pickAutoVoice(raw, lang);
}
